import { webkit, chromium } from "playwright";
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { extname, join, resolve } from "node:path";
const DOCS = resolve("../docs"), H = resolve("harness");
const MIME = { ".html": "text/html", ".js": "text/javascript", ".wasm": "application/wasm" };
const srv = createServer(async (q, r) => { const u = decodeURIComponent(new URL(q.url, "http://x").pathname);
  const p = u.startsWith("/harness/") ? join(H, u.slice(9)) : join(DOCS, u);
  try { r.writeHead(200, { "Content-Type": MIME[extname(p)] || "application/octet-stream" }).end(await readFile(p)); } catch { r.writeHead(404).end(); } });
await new Promise(r => srv.listen(0, "127.0.0.1", r));
const [file, ...planArgs] = process.argv.slice(2);
const raw = planArgs.join(" ");
const cmd = JSON.parse((await readFile("web-out/render-cmd.json", "utf8")));
const plan = raw.split(";;").map(s => s.trim()).filter(Boolean).map(s => s === "RENDER" ? JSON.stringify(cmd.args) : s);
const b = await webkit.launch(); const page = await (await b.newContext()).newPage();
await page.goto(`http://127.0.0.1:${srv.address().port}/harness/ff.html`); await page.waitForFunction(() => window.ready);
await page.setInputFiles("#f", file);
const res = await Promise.race([page.evaluate(([p, a]) => window.runPlan(p, a), [plan, cmd.ass]), new Promise(r => setTimeout(async () => r("TIMEOUT. partial:\n" + await page.locator("#o").textContent().catch(() => "?")), 240000))]);
console.log(res); await b.close().catch(() => {}); srv.close(); process.exit(0);
