import { chromium } from '../tests/node_modules/playwright/index.mjs';
import { spawn } from 'node:child_process';
import { mkdtemp, mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes, createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
const root=resolve(fileURLToPath(new URL('..',import.meta.url)));
const shots=join(root,'design/captures');await mkdir(shots,{recursive:true});
const jobs=await mkdtemp(join(tmpdir(),'clip-machine-marketing-'));
const key=randomBytes(24).toString('hex'),base='http://127.0.0.1:8790/';
try { await fetch(base+'api/info'); throw Error('Port 8790 is already occupied; refusing to reuse it.'); } catch(e) { if(e.message.includes('occupied'))throw e; }
const srv=spawn(join(root,'.venv/bin/python'),['app.py'],{cwd:root,env:{...process.env,CLIP_PORT:'8790',CLIP_JOBS:jobs,CLIP_KEY:key,CLIP_LOG:join(jobs,'results.json'),CLIP_STUDIO:join(jobs,'studio.json')},stdio:['ignore','pipe','pipe']});
let log='';srv.stdout.on('data',d=>log+=d);srv.stderr.on('data',d=>log+=d);
let browser;const errors=[];
try {
  let up=false;for(let i=0;i<60;i++){try{if((await fetch(base+'api/info?key='+key)).ok){up=true;break;}}catch{}await new Promise(r=>setTimeout(r,300));}if(!up)throw Error('Isolated server failed: '+log.slice(-1200));
  browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:2});page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'?key='+key);await page.waitForFunction(()=>document.body.classList.contains('desk'));
  await page.evaluate(()=>document.fonts.ready);
  await page.locator('.chips[data-k="model"] [data-v="tiny"]').dispatchEvent('click');
  await page.locator('.chips[data-k="n"] [data-v="3"]').click();
  await page.setInputFiles('#file',join(root,'tests/media/talk_80s.mp4'));
  await page.locator('.qi').first().waitFor();
  await page.mouse.move(1430,990);
  await page.screenshot({path:join(shots,'queue.png'),animations:'disabled'});
  await page.locator('#queue').screenshot({path:join(shots,'queue-detail.png'),animations:'disabled'});
  await page.click('#go');
  await page.waitForFunction(()=>document.querySelector('#prog').classList.contains('hide')&&document.querySelectorAll('#out .clip').length>0&&!document.querySelector('.qi[data-st="running"],.qi[data-st="queued"]'),null,{timeout:600000,polling:1000});
  await page.locator('#out').scrollIntoViewIfNeeded();
  await page.waitForFunction(()=>[...document.querySelectorAll('#out .clip video')].every(v=>v.readyState>=3),null,{timeout:30000});
  await page.evaluate(()=>{for(const v of document.querySelectorAll('#out .clip video')){v.pause();v.currentTime=Math.min(.5,v.duration/2);}});
  await page.waitForFunction(()=>[...document.querySelectorAll('#out .clip video')].every(v=>!v.seeking&&v.readyState>=3));
  await page.waitForFunction(()=>!document.querySelector('#toast').classList.contains('on'));
  await page.mouse.move(1430,990);
  await page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))));
  await page.screenshot({path:join(shots,'board.png'),animations:'disabled'});
  await page.locator('#findq').fill('the biggest mistake');
  await page.evaluate(()=>window.scrollTo(0,Math.max(0,document.querySelector('#findForm').getBoundingClientRect().top+scrollY-160)));
  await page.mouse.move(1430,990);await page.waitForTimeout(350);
  await page.screenshot({path:join(shots,'find.png'),animations:'disabled'});
  await page.locator('#findForm').screenshot({path:join(shots,'find-detail.png'),animations:'disabled'});
  await page.locator('#findq').fill('');
  const card=page.locator('#out .clip').first();
  await card.locator('details.more > summary').click();
  await card.locator('[data-nle]').scrollIntoViewIfNeeded();
  await page.mouse.move(1430,990);await page.waitForTimeout(350);
  await page.screenshot({path:join(shots,'handoff.png'),animations:'disabled'});
  await card.locator('details.more > summary').click();
  await card.locator('[data-edit]').click();await page.locator('#studio:not(.hide)').waitFor();
  await page.waitForFunction(()=>document.querySelector('#stVid').readyState>=2);
  await page.mouse.move(1430,990);await page.waitForTimeout(350);
  await page.screenshot({path:join(shots,'studio.png'),animations:'disabled'});
  const count=await page.locator('#out .clip').count();
  if(errors.length)throw Error(errors.join('\n'));
  const input=await readFile(join(root,'tests/media/talk_80s.mp4'));
  await writeFile(join(shots,'provenance.json'),JSON.stringify({captured_at:new Date().toISOString(),app_base_commit:'aff46fe',source:'tests/media/talk_80s.mp4',source_sha256:createHash('sha256').update(input).digest('hex'),source_rights:'Generated test fixture: ffmpeg testsrc2 and system TTS; see tests/make_media.sh. Not customer footage.',viewport:[1440,1000],device_scale_factor:2,port:8790,clips:count,page_errors:errors,notes:'Actual app UI and real native job. Find capture shows a typed query, not a fabricated successful result. Private job folders were never loaded.'},null,2)+'\n');
  console.log('PASS: real queue, board, studio, find input and editor hand-off captured; '+count+' clips; no page errors.');
} finally {if(browser)await browser.close();srv.kill('SIGTERM');await writeFile(join(jobs,'capture-server.log'),log);}
